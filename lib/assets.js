/** Build the web manifest served at /dsh-web-push/manifest.webmanifest. */
export function manifestSource() {
    return JSON.stringify({
        name: 'DeepSeek Harness',
        short_name: 'DSH',
        description: 'DeepSeek Harness web push notifications',
        start_url: '/',
        display: 'standalone',
        background_color: '#111318',
        theme_color: '#4D6BFE',
        icons: [
            { src: '/dsh-web-push/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
        ],
    }, null, 2);
}

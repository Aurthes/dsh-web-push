/**
 * Static web assets served by the plugin over webServer routes:
 *
 *   /dsh-web-push/sw.js                  — the service worker (push + click)
 *   /dsh-web-push/manifest.webmanifest   — minimal PWA manifest (A2HS / icons)
 *   /dsh-web-push/icon.svg               — notification + home-screen icon
 *
 * The service worker scope is /dsh-web-push/ (its own directory), which is all
 * the Push API needs: the subscription is bound to the registration, and the
 * `notificationclick` handler may open any same-origin URL (the DSH root '/').
 */
/** Build the service worker JavaScript served at /dsh-web-push/sw.js. */
export function serviceWorkerSource() {
    return `/* dsh-web-push service worker — generated by the dsh-web-push plugin */
self.addEventListener('install', () => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim())
})

// Origin liveness, probed once per worker lifetime: quick-tunnel restarts
// orphan this worker's domain, and opening ANY url on a dead origin lands on
// a Cloudflare error page (1016/1033). A dead-origin click is a silent no-op;
// opening DSH on the live URL re-subscribes and heals everything.
let originAlive = undefined // undefined = unknown, true/false = cached verdict
const probeOrigin = async () => {
  try {
    const res = await fetch('/dsh-web-push/sw.js', { cache: 'no-store' })
    originAlive = res.status === 200 // 404/5xx from the edge = dead tunnel
  } catch { originAlive = false } // network failure = dead domain
  return originAlive
}

self.addEventListener('push', (event) => {
  if (originAlive === undefined) void probeOrigin() // pre-warm; don't block display
  let data = {}
  try {
    data = event.data ? event.data.json() : {}
  } catch (error) {
    data = { title: 'DSH', body: event.data ? event.data.text() : '' }
  }
  const title = data.title || 'DSH'
  event.waitUntil(self.registration.showNotification(title, {
    body: data.body || '',
    tag: data.tag || 'dsh-web-push',
    renotify: true,
    icon: data.icon || '/dsh-web-push/icon.svg',
    badge: '/dsh-web-push/icon.svg',
    data: { url: data.url || '/', session: data.session },
  }))
})

self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  const data = event.notification.data || {}
  const url = data.url || '/'
  const sessionId = data.session
  event.waitUntil((async () => {
    if (originAlive === undefined) await probeOrigin()
    if (!originAlive) return // dead origin: no action beats an error page
    const clientList = await self.clients.matchAll({ type: 'window', includeUncontrolled: true })
    for (const client of clientList) {
      if ('focus' in client) {
        // Live tab: steer it in place — no reload, no lost drafts. The page
        // listens for 'dsh-web-push:open' and calls uiWorkspace.openSession.
        if (sessionId) {
          client.postMessage({ type: 'dsh-web-push:open', session: sessionId })
          return client.focus()
        }
        try { if (client.navigate && client.url !== new URL(url, self.location.origin).href) await client.navigate(url) } catch (error) {}
        return client.focus()
      }
    }
    // Cold open carries the session in the URL; the page's deep-link shim
    // reads it once on boot and switches to that session.
    return self.clients.openWindow(url)
  })())
})
`;
}
